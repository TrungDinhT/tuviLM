/** A star anchor in the artwork's 100×100 coordinate space. */
export type GodConstellationPoint = readonly [x: number, y: number, power?: number];

/**
 * A lightweight constellation traced over one god portrait. `lines` contain
 * indexes into `points`; the optional point power enlarges important stars.
 */
export interface GodConstellation {
  readonly points: readonly GodConstellationPoint[];
  readonly lines: readonly (readonly [from: number, to: number])[];
}

